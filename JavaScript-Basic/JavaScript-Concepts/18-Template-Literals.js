
// JavaScript Basic - Template Literals(use Backticks = ` ` )

// 1. Variables with Template Literals
let name = "Faraz";
let age = 25;

console.log(`My name is ${name}`);
console.log(`My age is ${age}`);

// 2. Combine Text and Variables
let city = "Patna";

console.log(`I live in ${city}`);

// 3. Calculation inside Template Literals
let num1 = 10;
let num2 = 20;

console.log(`Total: ${num1 + num2}`);

// 4. Multiple Lines
let message = `Hello Faraz!
Welcome to JavaScript.
Keep learning!`;

console.log(message);

// 5. Compare Values
let price = 100;
let quantity = 3;

console.log(`Total Price: ${price * quantity}`);