
// JavaScript Basic - Data Types

// 1. String: Text
let studentName = "Faraz";

// 2. Number: Numbers
let studentAge = 25;
let studentMarks = 85.5;

// 3. Boolean: true or false
let isLearningJavaScript = true;

// 4. Undefined: Value assign nahi ki gayi
let studentCity;

// 5. Null: Jaanbujhkar empty value
let selectedCourse = null;

// 6. Array: Multiple values
let subjects = ["JavaScript", "HTML", "CSS"];

// 7. Object: Related information
let student = {
    name: "Faraz",
    age: 25,
    course: "JavaScript"
};

// Output
console.log(studentName);
console.log(studentAge);
console.log(studentMarks);
console.log(isLearningJavaScript);
console.log(studentCity);
console.log(selectedCourse);
console.log(subjects);
console.log(student);

// Data type check karna
console.log(typeof studentName);
console.log(typeof studentAge);
console.log(typeof isLearningJavaScript);