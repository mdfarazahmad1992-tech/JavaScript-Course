
// JavaScript Basic - Loops

// 1. FOR LOOP
// 1 se 5 tak numbers print karega
for (let i = 1; i <= 5; i++) {
    console.log("For Loop:", i);
}

// 2. WHILE LOOP
// 1 se 5 tak numbers print karega
let j = 1;

while (j <= 5) {
    console.log("While Loop:", j);
    j++;
}

// 3. Table of 2
for (let i = 1; i <= 10; i++) {
    console.log("2 x", i, "=", 2 * i);
}