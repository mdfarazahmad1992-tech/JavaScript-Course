
// JavaScript Basic - Comparison Operators

let a = 10;
let b = 5;

// 1. Greater than (bada hai?)
console.log(a > b);

// 2. Less than (chhota hai?)
console.log(a < b);

// 3. Greater than or equal to
console.log(a >= 10);

// 4. Less than or equal to
console.log(b <= 5);

// 5. Equal value and equal type
console.log(10 === 10);

// 6. Not equal
console.log(10 !== 5);