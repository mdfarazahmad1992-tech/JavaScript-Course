
// JavaScript Basic - Logical Operators

// 1. AND (&&)
// Dono conditions true honi chahiye
let age = 25;
let hasID = true;

console.log("AND:", age >= 18 && hasID);

// 2. OR (||)
// Kam se kam ek condition true honi chahiye
let isWeekend = false;
let isHoliday = true;

console.log("OR:", isWeekend || isHoliday);

// 3. NOT (!)
// True ko false aur false ko true karta hai
let isRaining = false;

console.log("NOT:", !isRaining);

// 4. Extra Practice
console.log("AND Example:", true && false);
console.log("OR Example:", true || false);
console.log("NOT Example:", !true);