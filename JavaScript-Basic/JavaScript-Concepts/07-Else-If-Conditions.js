
// JavaScript Basic - Else If Conditions

// 1. Check Student Grades
let marks = 85;

if (marks >= 90) {
    console.log("Grade A");
} else if (marks >= 75) {
    console.log("Grade B");
} else if (marks >= 60) {
    console.log("Grade C");
} else if (marks >= 40) {
    console.log("Grade D");
} else {
    console.log("Fail");
}

// 2. Check Temperature
let temperature = 30;

if (temperature >= 40) {
    console.log("Very Hot");
} else if (temperature >= 30) {
    console.log("Hot");
} else if (temperature >= 20) {
    console.log("Pleasant Weather");
} else {
    console.log("Cold");
}

// 3. Check Age Category
let age = 16;

if (age >= 60) {
    console.log("Senior Citizen");
} else if (age >= 18) {
    console.log("Adult");
} else {
    console.log("Minor");
}